#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Нормализация порчи извлечённого текста (движок-уровень, доменно-нейтрально).

Три типа порчи, которые встречаются в PDF Минздрава:

  Тип 1 — РАЗРЯДКА: буквы слова разделены пробелами («н е й р о н»), иногда с
          артефактами «_». Детерминированно чиним: серию из >= 4 одиночных букв
          подряд склеиваем обратно в слово. Союзы («и/в/с»), инициалы («А.»),
          римские/арабские номера НЕ трогаем — порог серии (>=4) их отсекает.

  Тип 2 — УДВОЕНИЕ: каждая буква продублирована («ССттааддиияя» = «Стадия»).
          ОПАСНО: в русском есть законные удвоения (ссадина, рассеянный,
          аккумулятор, введение). Схлопываем ТОЛЬКО токен, целиком состоящий из
          пар одинаковых букв, И только если результат — произносимое слово.

  Тип 3 — ГЛИФОВАЯ ПОДМЕНА: латиница отрендерена кириллицей через битый cmap
          («Мапбагб» = Mandard, «Шуогак» = Dworak). Строками НЕ чинится — только
          детектируется и флагается на OCR.

Все функции — чистые (строка -> строка/счётчик), без знания о документе.
"""

from __future__ import annotations

import re
from typing import Tuple

# --- общие классы символов ---------------------------------------------------
_RE_LETTER = re.compile(r"[А-Яа-яЁёA-Za-z]")
_CYR = re.compile(r"[А-Яа-яЁё]")
_LAT = re.compile(r"[A-Za-z]")
_VOWELS_RU = set("аеёиоуыэюяАЕЁИОУЫЭЮЯ")
# одиночные символы-артефакты, встречающиеся ВНУТРИ разрядки (их выкидываем)
_ARTIFACT = set("_„“”‘’^™°|")


# ============================================================================
# Тип 1 — разрядка (letterspacing)
# ============================================================================

def _is_single_letter(tok: str) -> bool:
    return len(tok) == 1 and bool(_RE_LETTER.match(tok))


def collapse_letterspacing(text: str, min_run: int = 4) -> Tuple[str, int]:
    """Склеить серии одиночных БУКВ (>= min_run подряд) обратно в слово.

    Серия может включать одиночные символы-артефакты («_», «^» …) — они внутри
    серии выкидываются. Цифры серию РАЗРЫВАЮТ (римские/арабские номера, TNM
    «I 1 0 0» не трогаем). Серию склеиваем ТОЛЬКО если в ней есть хотя бы одна
    строчная буква: разрядка слова всегда содержит строчные («н е й р о н»), а
    последовательности заглавных одиночных букв — это, как правило, легитимные
    метки-столбцы/аббревиатуры (TNM «Т N М», «С П И Д»), их не трогаем.
    Возвращает (текст, число_склеек).
    """
    if " " not in text:
        return text, 0
    toks = text.split(" ")
    out, i, fixed = [], 0, 0
    while i < len(toks):
        j, letters, has_lower, cyr, lat = i, 0, False, 0, 0
        while j < len(toks):
            t = toks[j]
            if _is_single_letter(t):
                letters += 1
                has_lower = has_lower or t.islower()
                if _CYR.match(t):
                    cyr += 1
                else:
                    lat += 1
                j += 1
            elif len(t) == 1 and t in _ARTIFACT:
                j += 1
            else:
                break
        # Склеиваем только моноскриптовую серию строчных букв длиной >= min_run.
        # Моноскриптовость отсекает перечисления-метки типа «G, A и M в крови»
        # (латиница A/M вперемешку с русскими и/в), разрядка же слова — один
        # алфавит. Наличие строчной отсекает аббревиатуры заглавными (TNM).
        mono = (cyr == 0 or lat == 0)
        if letters >= min_run and has_lower and mono:
            out.append("".join(t for t in toks[i:j] if _is_single_letter(t)))
            fixed += 1
            i = j
        else:
            out.append(toks[i])
            i += 1
    return " ".join(out), fixed


# ============================================================================
# Тип 2 — равномерное удвоение (letter doubling)
# ============================================================================

def _pronounceable_ru(word: str) -> bool:
    """Грубая проверка «похоже на русское слово»: есть гласная, нет длинного
    прогона согласных, доля гласных в разумных пределах."""
    low = word.lower()
    if not _CYR.search(low):
        return False
    vowels = sum(1 for ch in word if ch in _VOWELS_RU)
    if vowels == 0:
        return False
    ratio = vowels / len(word)
    if ratio < 0.15 or ratio > 0.85:
        return False
    run = 0
    for ch in word:
        if _CYR.match(ch) and ch not in _VOWELS_RU:
            run += 1
            if run > 3:
                return False
        else:
            run = 0
    return True


_RE_AFFIX = re.compile(r"^([^А-Яа-яЁё]*)([А-Яа-яЁё]+)([^А-Яа-яЁё]*)$")


def _collapse_doubled_token(tok: str) -> str | None:
    """Если ядро токена целиком из пар одинаковых букв и схлопывается в
    произносимое слово — вернуть исправленный токен, иначе None."""
    m = _RE_AFFIX.match(tok)
    if not m:
        return None
    lead, core, trail = m.groups()
    if len(core) < 6 or len(core) % 2:
        return None
    # каждая соседняя пара — одинаковые буквы?
    if any(core[k] != core[k + 1] for k in range(0, len(core), 2)):
        return None
    collapsed = core[0::2]
    if not _pronounceable_ru(collapsed):
        return None
    return lead + collapsed + trail


def collapse_doubling(text: str) -> Tuple[str, int]:
    """Схлопнуть равномерно-удвоенные токены. Обычные слова с одним законным
    удвоением («ссадина») НЕ трогаются — они не являются целиком парными."""
    if not text:
        return text, 0
    out, fixed = [], 0
    for tok in text.split(" "):
        c = _collapse_doubled_token(tok)
        if c is not None and c != tok:
            out.append(c)
            fixed += 1
        else:
            out.append(tok)
    return " ".join(out), fixed


# ============================================================================
# Тип 3 — глифовая подмена (не чиним, только детект)
# ============================================================================

# биграммы, типичные для латиницы, отрендеренной кириллическими глифами
# (n->п, d->б, r->г, w->у/ш …). В нормальном русском крайне редки.
_CORRUPT_BIGRAMS = ("пб", "гб", "бг", "уо", "шуо", "апб", "агб", "пбаг", "оаг", "уог")
_RE_MIXED = re.compile(r"[A-Za-z][А-Яа-яЁё]|[А-Яа-яЁё][A-Za-z]")
# известные шкалы, вышедшие кракозяброй
_GLYPH_MARKERS = ("мапбагб", "шуогак", "буогак", "мапёагё")


def _is_glyph_token(tok: str) -> bool:
    core = tok.strip(".,;:()[]«»\"'-—%<>")
    low = core.lower()
    if low in _GLYPH_MARKERS:
        return True
    if len(core) >= 4 and _CYR.fullmatch(core) and \
            sum(1 for b in _CORRUPT_BIGRAMS if b in low) >= 1:
        return True
    return False


def glyph_suspect_count(text: str) -> int:
    """Число токенов с признаками глифовой подмены (кириллица из битого cmap)."""
    return sum(1 for tok in text.split() if _is_glyph_token(tok))


def looks_glyph_corrupted(text: str) -> bool:
    """Регион (заголовок/подпись/тело таблицы) похож на глифовую порчу.

    Порог намеренно консервативный, чтобы НЕ задеть чистые токены латиницы и
    редкие OCR-замены одной буквы («cводы») в нормальных файлах: нужен либо
    явный маркер, либо >= 2 подозрительных токена с заметной плотностью, либо
    массовое смешение скриптов.
    """
    toks = text.split()
    if not toks:
        return False
    suspect = sum(1 for t in toks if _is_glyph_token(t))
    if any(t.strip(".,;:()[]«»\"'-—%<>").lower() in _GLYPH_MARKERS for t in toks):
        return True
    mixed = len(_RE_MIXED.findall(text))
    ratio = suspect / len(toks)
    return mixed >= 3 or (suspect >= 2 and ratio >= 0.03)


# ============================================================================
# Тип 3б — ОБРАТНАЯ глифовая подмена: кириллица отрендерена битым cmap в
#          ASCII/псевдо-ASCII («D>AD>@=>-:0;LF852>3>» = «фосфорно-кальциевого»,
#          «Ʌ01>@0B>@=K5 4803=>AB8G5A:85» = «Лабораторные диагностические»).
#          В отличие от Типа 3 (латиница -> кириллица), эти токены кириллицы НЕ
#          содержат вовсе, поэтому биграммный детектор их не видит. Не чиним —
#          только детектируем; признак ПЛОТНОСТНОЙ (агрегатный по документу).
# ============================================================================

# «символьный мусор», в который битый cmap отображает частые кириллические
# буквы (о->>, е->5-подобные, я->O, . ->@ …). Скобки НЕ включаем — они законны
# в лаб-обозначениях «25(OH)D», «1,25(OH)2D».
_PSEUDO_JUNK = frozenset("><;:?@=")


def _is_significant_token(tok: str) -> bool:
    """Значимый (контентный) токен для знаменателя плотности: длина >= 4 и есть
    хотя бы один буквенно-цифровой символ. Короткие служебные слова, одиночные
    цифры/номера страниц и голая пунктуация в долю не идут — иначе шум
    занижал/завышал бы долю случайно."""
    return len(tok) >= 4 and any(ch.isalnum() for ch in tok)


def _is_pseudo_ascii_token(tok: str) -> bool:
    """Токен похож на кириллицу, отрисованную в ASCII/псевдо-ASCII: длина >= 4,
    кириллицы нет вовсе, и внутри СКЛЕЕНЫ (по определению токена — без пробелов)
    И цифры, И «символьный мусор» (> < ; : ? @ =).

    Описание намеренно ловит и одиночные лаб-токены («>50%», «p<0.05», «[1-7]:»),
    поэтому НА ТОКЕН-УРОВНЕ это НЕ решение о порче: отсекает единичные лаб-токены
    ПЛОТНОСТНОЙ порог (см. pseudo_ascii_glyph_tokens), а не признак токена."""
    if len(tok) < 4 or _CYR.search(tok):
        return False
    has_digit = any(ch.isdigit() for ch in tok)
    has_junk = any(ch in _PSEUDO_JUNK for ch in tok)
    return has_digit and has_junk


def pseudo_ascii_counts(text: str) -> Tuple[int, int]:
    """(число значимых токенов, число псевдо-ASCII токенов) в регионе.

    Счётчики аккумулируются по документу — решение о порче принимается по
    СОВОКУПНОЙ доле (pseudo_ascii_glyph_tokens), а не по отдельному региону."""
    sig = pseudo = 0
    for tok in text.split():
        if _is_significant_token(tok):
            sig += 1
            if _is_pseudo_ascii_token(tok):
                pseudo += 1
    return sig, pseudo


# Порог плотности «обратной» глифовой порчи. Замер по корпусу (722 PDF):
#   - два тотально-битых файла: доля 0.69 и 0.64;
#   - самый «шумный» ЗДОРОВЫЙ файл (частичный скан + лаб-обозначения) — 0.055;
#   - домен-двойник по витамину D (масса «25(OH)D», «COVID-19», сравнений) — 0.012.
# Порог 0.30 лежит в рекомендованном диапазоне 0.30–0.40 и оставляет >5x запас
# над здоровыми (0.055) и >2x под битыми (0.64). Абсолютный минимум токенов
# страхует от крошечного текстового слоя (пара OCR-огрызков дала бы ложную долю).
_PSEUDO_DENSITY_MIN = 0.30
_PSEUDO_MIN_TOKENS = 30


def pseudo_ascii_glyph_tokens(sig_total: int, pseudo_total: int) -> int:
    """Сколько псевдо-ASCII токенов засчитать «на OCR» по документу в целом.

    Возвращает pseudo_total ТОЛЬКО при тотальной порче — доля значимых токенов
    >= порога И абсолютное число >= минимума; иначе 0. Так единичные лаб-токены
    («>50%», «p<0.05») в здоровом документе порог не дают."""
    if pseudo_total < _PSEUDO_MIN_TOKENS or sig_total <= 0:
        return 0
    if pseudo_total / sig_total < _PSEUDO_DENSITY_MIN:
        return 0
    return pseudo_total


# ============================================================================
# Тип 3в — КИРИЛЛО-ЛАТИНСКАЯ глиф-мешанина с впаянным «§» (U+00A7).
#          Битый шрифт-слой оригинала рендерит латинские шкалы/аббревиатуры
#          кирилло-латинской кашей, в которую впаивается знак параграфа:
#          BCLC->ВСЬС, HBsAg->НВзА§, Child-Pugh->Ри§Ь, IgM/IgG->1§М/1§С,
#          Allergy->А11ег§у. Не чиним — только детектируем; признак ПЛОТНОСТНОЙ
#          (агрегатный по документу, ОБЯЗАТЕЛЬНО включая references/excluded).
# ============================================================================

_SECTION_SIGN = "§"  # «§» — маркер впаянного битого глифа


def _is_section_sign_glyph_token(tok: str) -> bool:
    """Токен с впаянным «§»: содержит U+00A7 И хотя бы один буквенно-цифровой
    символ в том же токене. Почти всегда битый кирилло-латинский глиф. Голый «§»
    (сноска, обозначение) сюда НЕ попадает — нужен alnum внутри токена. Единичные
    легитимные случаи (турецкая фамилия «Demirba§» в references, сноска
    «Цисплатин**§») отсекаются не здесь, а ПЛОТНОСТНЫМ порогом ниже."""
    return _SECTION_SIGN in tok and any(ch.isalnum() for ch in tok)


def section_sign_counts(text: str) -> Tuple[int, int]:
    """(число значимых токенов, число токенов с впаянным «§») в тексте.

    Знаменатель — значимые токены (_is_significant_token, общий с pseudo_ascii);
    числитель считается по ВСЕМ токенам (короткий «1§М» = IgM тоже глиф). Решение
    о порче — по СОВОКУПНОЙ доле (section_sign_glyph_tokens), не по региону."""
    sig = glyph = 0
    for tok in text.split():
        if _is_significant_token(tok):
            sig += 1
        if _is_section_sign_glyph_token(tok):
            glyph += 1
    return sig, glyph


# Порог плотности «§-в-токене». Замер по корпусу (701 PDF):
#   - эталоны порчи: 6.0..28.2 §-токенов на 1000 значимых (мин КР957_1 6.0);
#   - самый «шумный» ЗДОРОВЫЙ файл (легит-латиница, фамилии в references) — <0.5;
#   - здоровые с 66-120 легит. лат. токенов (КР1000_1 и др.) — ровно 0.
# Порог 2.0/1000 даёт >2x запас над здоровыми и уверенно ловит эталоны (мин 6.0).
# Абс. минимум §-токенов страхует от единичных легит-§ (Demirba§, сноска **§).
_SECTION_SIGN_DENSITY_MIN = 0.002   # 2.0 §-токенов на 1000 значимых
_SECTION_SIGN_MIN_TOKENS = 5        # абсолютный минимум §-токенов


def section_sign_glyph_tokens(sig_total: int, glyph_total: int) -> int:
    """Сколько «§-в-токене» засчитать «на OCR» по документу в целом.

    Возвращает glyph_total ТОЛЬКО при доле значимых токенов >= порога И абс. числе
    >= минимума; иначе 0. Так единичные легитимные «§» (фамилии/сноски) в здоровом
    документе порог не дают."""
    if glyph_total < _SECTION_SIGN_MIN_TOKENS or sig_total <= 0:
        return 0
    if glyph_total / sig_total < _SECTION_SIGN_DENSITY_MIN:
        return 0
    return glyph_total


# ============================================================================
# Тип 5 — УПРАВЛЯЮЩИЕ СИМВОЛЫ C0 вместо букв (битый cmap отдаёт код глифа).
#         «Chlamydia» -> «Hhl\x12m\x1adi\x12», «Registry» -> «R\x07gistr\x1a».
#         Ни один из прежних детекторов сюда не смотрит: кириллицы нет, псевдо-
#         ASCII нет, «§» нет. Строкой НЕ чинится (соответствие код->буква своё у
#         каждого сабсета шрифта) — только считается и уходит в гейт валидатора.
# ============================================================================

# Форматные символы без графемы: их удаление текст не меняет (нулевая ширина,
# направление письма, мягкий перенос уже снят в pdf_reader). Удаляем молча.
_FORMAT_CHARS = frozenset("​‌‍‎‏⁠﻿­")


def strip_format_chars(text: str) -> Tuple[str, int]:
    """Убрать невидимые форматные символы. Возвращает (текст, сколько убрано)."""
    if not any(ch in _FORMAT_CHARS for ch in text):
        return text, 0
    kept = [ch for ch in text if ch not in _FORMAT_CHARS]
    return "".join(kept), len(text) - len(kept)


def control_char_count(text: str) -> int:
    """Число символов C0/C1 (кроме \\n \\t \\r) в строке.

    Это НЕ форматные символы, а подстановка вместо букв: удалять их нельзя —
    склеятся соседние токены и порча станет невидимой. Считаем и флагуем."""
    return sum(1 for ch in text
               if (ch < " " or "" <= ch <= "") and ch not in "\n\t\r")


# ============================================================================
# Составной нормализатор для одной строки (Тип 1 + Тип 2)
# ============================================================================

def normalize_line(text: str) -> Tuple[str, int, int]:
    """Применить к строке разрядку и удвоение. Глифовую порчу НЕ трогаем.

    Возвращает (текст, число_склеек_разрядки, число_схлопываний_удвоения).
    """
    text, n_sp = collapse_letterspacing(text)
    text, n_db = collapse_doubling(text)
    return text, n_sp, n_db
