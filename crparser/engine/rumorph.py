#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЯЗЫКОВОЙ АРБИТР русского языка (ГЕЙТ 2 канала C5) — тонкая обёртка над pymorphy3.

ЗАЧЕМ. Порча класса C5 («латинское слово ЦЕЛИКОМ кириллицей»: `йуег`->liver,
`уапсез`->varices) структурно НЕОТЛИЧИМА от русского слова, а глифы русского текста в
битом документе рендерятся ВЕРНО (порча сидит в /ToUnicode) — значит ВИЗУАЛЬНЫЙ метод
(любой OCR) видит правильный русский и отличить его от правильной латиницы НЕ МОЖЕТ
(I21). Отличает только ЯЗЫК. Это доказано двумя откатами: рукодельная карта
транслитерации латинизировала 196 рус. словоформ, второе мнение движка `-l rus` дало
`боль`->`bone`.

ПОЧЕМУ `word_is_known()`, А НЕ РАЗБОР. У pymorphy есть предсказатель по суффиксам,
который «узнаёт» ЛЮБОЙ мусор — замерено на нашем же корпусе порчи:

    оезорЬадиз  is_known=False  score=1.000  NOUN,anim,masc,Name  (принял за фамилию!)
    ГЦР         is_known=False  score=1.000  UNKN
    уапсез      is_known=False  score=0.500  NOUN,inan,masc,sing,nomn

score предсказателя у ПОРЧИ доходит до 1.000 — выше, чем у настоящего рус. слова
`гепатоцеллюлярном` (0.494). Любой гейт по `parse()`/score пропустил бы порчу и/или
утопил русский. `word_is_known()` спрашивает СЛОВАРНУЮ базу (OpenCorpora, ~5 млн
словоформ) и предсказатель НЕ включает — только он и годится.

ГРАНИЦА ГЕЙТА (ЗАМЕРЕНО, обязательно к прочтению перед правкой).
`word_is_known()` — это СЛОВАРЬ общего языка, и МЕДИЦИНСКОЙ лексики в нём НЕТ:

    боль/пациентов/Уровень/Клинические/печени/СОСТАВ/РФ ....... known=True   (защищены)
    гепатоцеллюлярном/стеатогепатита/мультикиназными .......... known=False  (НЕ защищены)
    холангиокарцинома/иммуногистохимического/ГЦР/СНВС ......... known=False  (НЕ защищены)

Значит гейт 2 закрывает ОБЩИЙ русский (и ровно те слова, на которых канал падал:
`боль`->`bone`, `пациентов`->`nayuenmoe`, `Уровень`->`ypoBeHb`), а МЕДИЦИНСКИЙ русский
держат другие гейты стека (частотность в документе, транслит-артефакт, LAT-словарь).
Утверждение «морфоанализатор знает любую словоформу независимо от частоты» ВЕРНО только
для лемм, которые есть в OpenCorpora. Не расширять зону ответственности этого гейта.

FAIL-CLOSED (I5). Если pymorphy3 недоступен — `available()` False, и канал C5 обязан
ВЫКЛЮЧИТЬСЯ ЦЕЛИКОМ. Трактовать «пакета нет» как «слово неизвестно» = латинизировать
русский на машине без зависимости и молча произвести ДРУГОЙ корпус (ровно дыра I5, где
отсутствующий Tesseract давал exit 0 и другой выход).
"""

from __future__ import annotations

from typing import Optional

_ANALYZER: Optional[object] = None
_TRIED = False
_ERR: str = ""


def _analyzer():
    """Ленивый синглтон MorphAnalyzer (инициализация ~0.3с + словарь; в батче каждый
    воркер-процесс греет свой). Пакета нет -> None, БЕЗ исключения."""
    global _ANALYZER, _TRIED, _ERR
    if _TRIED:
        return _ANALYZER
    _TRIED = True
    try:
        import pymorphy3
        _ANALYZER = pymorphy3.MorphAnalyzer()
    except Exception as exc:  # noqa: BLE001
        _ANALYZER = None
        _ERR = repr(exc)
    return _ANALYZER


def available() -> bool:
    """Арбитр доступен? False -> канал C5 ОБЯЗАН быть выключен (fail-closed, I5)."""
    return _analyzer() is not None


def why_unavailable() -> str:
    _analyzer()
    return _ERR


def word_is_known(word: str) -> bool:
    """Токен — РЕАЛЬНАЯ русская словоформа по словарю OpenCorpora?

    True -> ГЕЙТ 2 закрыт: C5 НЕ ИМЕЕТ ПРАВА трогать токен НИКОГДА (`боль` остаётся
    `боль`, `bone` невозможен). False -> НЕ доказано, что это русский; решают
    остальные гейты стека (не «значит порча»!).

    Арбитр недоступен -> True (fail-closed: считаем русским = не трогаем)."""
    a = _analyzer()
    if a is None:
        return True
    w = (word or "").strip().lower()
    if not w:
        return True
    # ё/е: проверяем ОБА написания и защищаем, если знакомо ХОТЬ ОДНО (источник пишет
    # и «ёлка», и «елка»; словарь несёт ё-формы). Сомнение трактуем в пользу защиты.
    forms = {w}
    if "ё" in w:
        forms.add(w.replace("ё", "е"))
    try:
        return any(a.word_is_known(f) for f in forms)
    except Exception:  # noqa: BLE001
        return True
